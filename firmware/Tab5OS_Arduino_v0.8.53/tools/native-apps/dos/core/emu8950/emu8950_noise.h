static const uint32_t opl_noise_jump2[4] = {
    0x000000u, 0x200080u, 0x400100u, 0x600180u
};

static inline uint32_t opl_noise_advance14(uint32_t noise)
{
    noise = (noise >> 7) ^ opl_noise_jump7[noise & 127u];
    return (noise >> 7) ^ opl_noise_jump7[noise & 127u];
}
static inline uint32_t opl_noise_advance2(uint32_t noise)
{
    return (noise >> 2) ^ opl_noise_jump2[noise & 3u];
}
