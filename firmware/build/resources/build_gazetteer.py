#!/usr/bin/env python3
"""Build a bounded random-access Tab5 gazetteer from the original GeoNames cities ZIP.

Data: GeoNames, CC BY 4.0. No network access is performed by this generator.
All city names and alternate names are indexed; the source ZIP is required.
"""
from pathlib import Path
import argparse,datetime,hashlib,json,math,struct,unicodedata,zipfile
MAGIC=b'T5GEO01\0';HEADER=64;MAX_KEY=159;MAX_NAME=95
SPECIAL={ord(a):b for a,b in [('Æ','ae'),('æ','ae'),('Œ','oe'),('œ','oe'),('Ø','o'),('ø','o'),('Ł','l'),('ł','l'),('Ð','d'),('ð','d'),('Þ','th'),('þ','th'),('Đ','d'),('đ','d'),('ı','i'),('ſ','s')]}
def fold_table():
 out={}
 for cp in list(range(0x80,0x530))+list(range(0x1e00,0x2000)):
  if 0x300<=cp<=0x36f:continue
  c=chr(cp);s=SPECIAL.get(cp,''.join(x for x in unicodedata.normalize('NFKD',c.casefold()) if not unicodedata.combining(x)))
  if s!=c and len(s.encode())<=4:out[cp]=s
 return out
FOLD=fold_table()
def normalize(s):
 parts=[]
 for c in s:
  cp=ord(c)
  if 0x300<=cp<=0x36f:continue
  if cp<32 or cp==127:return ''
  if cp<128:
   parts.append(c.lower() if c.isalnum() else ' ')
  elif cp in (0x85,0xa0,0x1680,0x3000) or 0x2000<=cp<=0x206f:parts.append(' ')
  else:parts.append(FOLD.get(cp,c))
 return ' '.join(x for x in ''.join(parts).split(' ') if x)
def utf8_limit(s,n):return s.encode()[:n].decode('utf-8','ignore')
def generate(source,target,fold_header=None):
 data=source.read_bytes();records=[];keys=set();source_rows=0
 with zipfile.ZipFile(source) as z:
  member=next(n for n in z.namelist() if n.startswith('cities') and n.endswith('.txt'))
  for raw in z.read(member).decode('utf-8').splitlines():
   source_rows+=1;f=raw.split('\t')
   if len(f)<19 or f[6]!='P':continue
   try:gid=int(f[0]);lat=float(f[4]);lon=float(f[5]);pop=min(0xffffffff,max(0,int(f[14])))
   except ValueError:continue
   if not math.isfinite(lat+lon) or abs(lat)>85.051129 or abs(lon)>180:continue
   name=utf8_limit(f[1],MAX_NAME);country=f[8].encode('ascii','ignore')[:2].ljust(2,b' ')
   area=utf8_limit('/'.join(x for x in (f[10],f[11]) if x),31)
   if not name:continue
   index=len(records);records.append((gid,name,country,area,round(lat*1e6),round(lon*1e6),pop))
   names={f[1],f[2],*f[3].split(',')}
   # Canonical word suffixes make multiword names discoverable without a full scan.
   for canonical in (f[1],f[2]):
    words=normalize(canonical).split()
    for i in range(1,min(4,len(words))):
     if len(words[i])>=3:names.add(' '.join(words[i:]))
   for candidate in names:
    key=normalize(candidate).encode('utf-8')
    if 2<=len(key)<=MAX_KEY:keys.add((key,index))
 keys=sorted(keys)
 key_data=bytearray();key_offsets=[]
 for key,index in keys:
  key_offsets.append(len(key_data));_,_,_,_,lat,lon,pop=records[index]
  key_data.extend(struct.pack('<IiiIB',index,lat,lon,pop,len(key)));key_data.extend(key)
 place_data=bytearray();place_offsets=[]
 for gid,name,country,area,lat,lon,pop in records:
  place_offsets.append(len(place_data));name=name.encode();area=area.encode()
  place_data.extend(struct.pack('<IB2sB',gid,len(name),country,len(area)));place_data.extend(name);place_data.extend(area)
 key_index=HEADER;key_start=key_index+len(keys)*4;place_index=key_start+len(key_data);place_start=place_index+len(records)*4;size=place_start+len(place_data)
 header=struct.pack('<8s10I',MAGIC,1,HEADER,len(records),len(keys),key_index,key_start,place_index,place_start,size,MAX_KEY).ljust(HEADER,b'\0')
 target.parent.mkdir(parents=True,exist_ok=True)
 with target.open('wb') as out:
  out.write(header)
  for x in key_offsets:out.write(struct.pack('<I',x))
  out.write(key_data)
  for x in place_offsets:out.write(struct.pack('<I',x))
  out.write(place_data)
 if fold_header:
  lines=['#pragma once','#include <cstdint>','// Generated by build/resources/build_gazetteer.py; keep generator and runtime normalization identical.','namespace Tab5GeoIndex {','struct Fold {uint16_t code;uint8_t length;char text[4];};','static constexpr Fold folds[] = {']
  for cp,s in sorted(FOLD.items()):
   b=s.encode();codes=','.join('char(0x%02x)'%x for x in b);lines.append('  {0x%04x,%d,{%s}},'%(cp,len(b),codes))
  lines+=['};','}'];fold_header.write_text('\n'.join(lines)+'\n')
 report=dict(source='https://download.geonames.org/export/dump/'+source.name,generatorSha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),sourceSha256=hashlib.sha256(data).hexdigest(),sourceBytes=len(data),sourceMember=member,sourceRows=source_rows,places=len(records),keys=len(keys),bytes=size,sha256=hashlib.sha256(target.read_bytes()).hexdigest(),license='CC-BY-4.0',attribution='GeoNames — https://www.geonames.org/',builtAt=datetime.datetime.now(datetime.timezone.utc).isoformat(),unicodeVersion=unicodedata.unidata_version,scope='World cities1000: population above 1000 or administrative seats; WGS84, Mercator latitude range. Names/alternate names and canonical word suffixes; no streets/addresses or exhaustive POIs.')
 if fold_header:report['foldHeaderSha256']=hashlib.sha256(fold_header.read_bytes()).hexdigest()
 target.with_suffix('.json').write_text(json.dumps(report,indent=2,ensure_ascii=False)+'\n');return report
if __name__=='__main__':
 a=argparse.ArgumentParser();a.add_argument('source',type=Path);a.add_argument('target',type=Path);a.add_argument('--fold-header',type=Path);o=a.parse_args();print(json.dumps(generate(o.source,o.target,o.fold_header),indent=2))
