"""Generate the firmware English dictionary from the complete editable pack."""
from pathlib import Path
import argparse,json
p=argparse.ArgumentParser();p.add_argument('sketch',type=Path);a=p.parse_args()
pack=json.loads((a.sketch/'sdcard/System/languages/en-US.json').read_text(encoding='utf8'))
rows=['  {'+json.dumps(k,ensure_ascii=False)+', '+json.dumps(v,ensure_ascii=False)+'}' for k,v in sorted(pack['translations'].items(),key=lambda x:x[0].encode('utf8')) if k!=v]
header='// Generated by build/resources/generate_locale_fallback.py from the editable English SD pack.\n#pragma once\nstruct Tab5EnglishEntry { const char* source; const char* translated; };\nstatic const Tab5EnglishEntry TAB5_ENGLISH_FALLBACK[] = {\n'+',\n'.join(rows)+'\n};\n'
(a.sketch/'Tab5EnglishFallback.h').write_text(header,encoding='utf8',newline='\n')
print('Generated English fallback:',len(rows),'translated entries from',len(pack['translations']),'reference labels.')
