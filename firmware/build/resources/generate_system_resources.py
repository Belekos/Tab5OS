"""Generate the firmware's bounded missing-file recovery payload from sdcard.

Run after updating Python modules and the release manifest. No fonts, ELF
applications, encyclopaedias, documents or user settings are embedded.
"""
from pathlib import Path
import argparse
import json
import unicodedata
import zlib


def generate(sketch):
    sd = sketch / "sdcard"
    files = sorted((sd / "MicroPython").rglob("*.py"))
    files += [sd / "System" / name for name in (
        "themes.json", "map_styles.json", "maps.ini", "python-catalog.json")]
    chunks = ["// Generated by build/resources/generate_system_resources.py.\n#pragma once\n#include <stddef.h>\n#include <stdint.h>\n",
              "struct Tab5SystemResource { const char* path; const uint8_t* data; size_t packedSize; size_t size; };\n"]
    entries = []
    packed_bytes = 0
    for n, path in enumerate(files):
        data = path.read_bytes()
        data.decode("utf-8")
        if len(data) > 128 * 1024:
            raise ValueError("System seed file too large: " + str(path))
        packed = zlib.compress(data, 9)
        packed_bytes += len(packed)
        symbol = "TAB5_RESOURCE_" + str(n)
        literals = "\n".join("  " + ",".join(f"0x{x:02x}" for x in packed[p:p+24]) + "," for p in range(0,len(packed),24))
        chunks.append(f'static const uint8_t {symbol}[] = {{\n{literals}\n}};\n')
        relative = "/" + path.relative_to(sd).as_posix()
        entries.append(f'  {{{json.dumps(relative)}, {symbol}, sizeof({symbol}), {len(data)}}}')
    chunks.append("static const Tab5SystemResource TAB5_SYSTEM_RESOURCES[] = {\n" + ",\n".join(entries) + "\n};\n")
    (sketch / "Tab5SystemResourcesData.h").write_text("".join(chunks), encoding="utf-8", newline="\n")

    # Built-in bitmap fonts cannot be assumed to cover typographic punctuation
    # or accents. Preserve printf placeholders while producing plain ASCII.
    pack = json.loads((sd / "System/languages/en-US.json").read_text(encoding="utf-8"))
    punctuation = str.maketrans({"−": "-", "–": "-", "—": "-", "…": "...", "•": "*", "·": "-", "’": "'", "‘": "'", "“": '"', "”": '"', "×": "x", "÷": "/", "→": "->", "←": "<-", "≥": ">=", "≤": "<=", "°": " deg"})
    rows = []
    for source, translated in sorted(pack["translations"].items(), key=lambda item: item[0].encode("utf-8")):
        translated = unicodedata.normalize("NFKD", translated.translate(punctuation)).encode("ascii", "ignore").decode("ascii")
        rows.append("  {" + json.dumps(source, ensure_ascii=False) + ", " + json.dumps(translated) + "}")
    content = "// Generated English fallback for the built-in bitmap font.\n#pragma once\nstatic const Tab5EnglishEntry TAB5_ENGLISH_BITMAP[] = {\n" + ",\n".join(rows) + "\n};\n"
    (sketch / "Tab5EnglishBitmap.h").write_text(content, encoding="utf-8", newline="\n")
    print(f"Embedded {len(files)} support files; {sum(p.stat().st_size for p in files)} source bytes; {packed_bytes} compressed bytes.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("sketch", type=Path)
    generate(parser.parse_args().sketch)
