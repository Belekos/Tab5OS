#!/usr/bin/env python3
"""Regenerate the English flash fallback after editing the English SD pack."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
pack = json.loads((root / "sdcard/System/languages/en-US.json").read_text(encoding="utf-8"))
rows = sorted(((key, value) for key, value in pack["translations"].items()
               if isinstance(value, str) and value and key != value),
              key=lambda row: row[0].encode("utf-8"))
quote = lambda text: json.dumps(text, ensure_ascii=False).replace("\\/", "/")
lines = ["// Generated by tools/generate_locale_fallback.py from the editable English SD pack.",
         "#pragma once", "struct Tab5EnglishEntry { const char* source; const char* translated; };",
         "static const Tab5EnglishEntry TAB5_ENGLISH_FALLBACK[] = {"]
lines.extend("  {" + quote(key) + ", " + quote(value) + "}," for key, value in rows)
lines.append("};")
(root / "Tab5EnglishFallback.h").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(str(len(rows)) + " English fallback entries")
